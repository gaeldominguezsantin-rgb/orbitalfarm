    id: str
    name_en: str
    name_es: str
    scientific_name: str
    family: str
    group: str              # cereal | legume | oilseed | cover | tuber
    season_affinity: str    # warm | cool | flexible
    kc_ini: float
    kc_mid: float
    kc_end: float
    root_depth_m: float
    gdd_base_c: float
    gdd_required: float
    t_opt_min_c: float
    t_opt_max_c: float
    t_heat_limit_c: float
    t_frost_limit_c: float
    drought_tolerance: float  # 0.0 (sensitive) to 1.0 (very hardy)
    ph_min: float
    ph_max: float
    n_net_kg_ha: float        # + = net N added via fixation/residue; - = N uptake
    som_delta_pct: float      # Seasonal SOM% contribution (residue minus tillage loss)
    residue_cover: float      # 0-1 surface mulch carryover for next season
    economic_index: float     # 0-1 relative farm revenue / market demand
    food_security_score: float  # 0-1 caloric/protein value for household resilience
    root_morphology: str      # fibrous | taproot | nodulated | tuberous
    color_hex: str            # Botanical visualization palette color
    notes_en: str
    notes_es: str


